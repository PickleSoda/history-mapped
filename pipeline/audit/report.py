"""report.md and story-fixes.md for the identity audit."""
from __future__ import annotations

import re
import time
from collections import Counter
from typing import Any


def _md_cell(v: Any) -> str:
    if isinstance(v, (list, tuple)):
        v = ", ".join(str(x) for x in v)
    s = "" if v is None else str(v)
    return s.replace("|", "\\|").replace("\n", " ")[:140]


def _table(items: list[dict[str, Any]], cols: list[str], n: int = 20) -> str:
    if not items:
        return "_none_\n"
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for it in items[:n]:
        lines.append("| " + " | ".join(_md_cell(it.get(c)) for c in cols) + " |")
    if len(items) > n:
        lines.append(f"\n_…{len(items) - n} more in the CSV._")
    return "\n".join(lines) + "\n"


def _note_file(path) -> list[str]:
    """Hand-written notes (one per line) kept next to the outputs, so a re-run keeps them."""
    if not path.exists():
        return []
    return [line.strip().lstrip("- ") for line in path.read_text().splitlines() if line.strip()]


def _source(created_by: str) -> str:
    m = re.match(r"pipeline:(?:recovery-\d+:)?(campaign_e\d+|[a-z_]+?)(?:__|$)", created_by or "")
    return m.group(1) if m else (created_by or "-").split(":")[0]


def _rule_key(rule: str, verdict: str) -> str:
    """'W8 far era (124y apart): another person …' -> 'W8 far era'."""
    if not rule:
        return verdict
    words = re.sub(r"\s*\(.*?\)", "", rule).replace(":", "").split()
    return " ".join(words[:5])


def write_report(audit, sections) -> None:
    R = audit.results
    out = audit.out
    before, after = R.get("inventory_before", {}), R.get("inventory_after")
    lines = [f"# Identity audit — {time.strftime('%Y-%m-%d %H:%M')}", "",
             "Generated by `python -m pipeline.audit identity`. Runbook: "
             "`docs/implementation-docs/identity-audit.md`. Local DB only.", ""]
    lines += ["## Counts (C1)", "", "| | before | after |", "|---|---|---|"]
    for key in ("entities", "with_qid", "distinct_qids", "qids_on_2plus_rows"):
        lines.append(f"| {key} | {before.get(key, '')} | {after.get(key, '') if after else '—'} |")
    for st in sorted(set(before.get("by_status", {})) | set((after or {}).get("by_status", {}))):
        lines.append(f"| status {st} | {before.get('by_status', {}).get(st, 0)} | "
                     f"{(after or {}).get('by_status', {}).get(st, 0) if after else '—'} |")
    lines += ["", "Per-type counts: `inventory-before.json`" + (", `inventory-after.json`" if after else "") + ".", ""]

    flags = R.get("qid_flags")
    if flags is not None:
        verdicts = Counter(f["verdict"] for f in flags)
        rules = Counter(_rule_key(f["rule"], f["verdict"]) for f in flags)
        actions = Counter((f.get("action") or "-").split(":")[0] for f in flags)
        checked = before.get("with_qid") or sum(1 for r in audit.rows.values() if r.qid)
        lines += ["## QID identity (C2, C3) — `qid-flags.csv`", "",
                  f"Checked {checked if not audit.limit else audit.limit} rows with a QID. "
                  f"Verdicts: {dict(verdicts)}.", "",
                  "| rule | rows |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(rules.items())]
        lines += ["", "Planned actions: " + ", ".join(f"{k} {v}" for k, v in actions.most_common()), ""]
        wrong = [f for f in flags if f["verdict"] == "wrong"]
        lines += ["**Wrong QIDs** (top 20):", "",
                  _table(wrong, ["name", "entity_type", "qid", "wd_label", "rule", "action", "proposed_qid"])]
        sus = [f for f in flags if f["verdict"] == "suspect" and f["severity"] == "medium"]
        lines += [f"**Suspect, medium** ({len(sus)}; top 20):", "",
                  _table(sus, ["name", "entity_type", "qid", "wd_label", "rule", "row_start", "wd_start"])]
        src = Counter(_source(f.get("created_by", "")) for f in wrong)
        lines += ["Wrong QIDs by creating run family: " + ", ".join(f"{k} {v}" for k, v in src.most_common(8)), ""]

    places = R.get("places")
    if places is not None:
        acts = Counter(f["action"] for f in places)
        lines += ["## Same-name places (C2b) — `place-flags.csv`", "",
                  f"{len(places)} city rows whose QID's description names no place in the row's text: "
                  + ", ".join(f"{k} {v}" for k, v in acts.most_common()) + ". `pin_candidate` = exactly one "
                  "other same-named place is described where the text says; verified ones are applied as pins. "
                  "`flag` alone is noisy (a description and a summary often name different levels: "
                  "'Hesse, Germany' vs 'East Francia').", "",
                  _table([f for f in places if f["action"] != "flag"],
                         ["name", "qid", "wd_description", "proposed_qid", "proposed_description", "action"], n=40)]

    applied = R.get("applied")
    if applied is not None:
        ok = [a for a in applied if a["status"] == "applied"]
        by_fix = Counter((a["fix"], a["column"]) for a in ok)
        lines += ["## Safe fixes applied (C9) — `applied.csv`, `qid-fixes-applied.csv`, `rollback.sql`", "",
                  f"Backup: `{R.get('backup', '').split('/')[-1]}`. {len(ok)} column changes, "
                  f"{len(applied) - len(ok)} skipped.", "",
                  "| fix | column | changes |", "|---|---|---|"] + \
            [f"| {f} | {c} | {n} |" for (f, c), n in sorted(by_fix.items())]
        rc = R.get("recheck", [])
        lines += ["", f"Re-check of {len(R.get('recheck_ids', []))} changed rows: "
                      f"{dict(Counter(f['verdict'] for f in rc))} non-clean (`qid-recheck.csv`).", ""]
        lines += [_table([a for a in ok if a["column"] == "wikidata_id"], ["id", "old", "new", "reason"])]

    dups = R.get("dups")
    if dups is not None:
        cats = Counter((d["category"], d["confidence"]) for d in dups)
        lines += ["## Duplicates (C4) — `duplicates.csv` (merge commands for the user)", "",
                  f"{len(dups)} proposed merges in {len({d['group'] for d in dups})} groups: " +
                  ", ".join(f"{c}/{conf} {n}" for (c, conf), n in sorted(cats.items())), "",
                  _table([d for d in dups if d["confidence"] != "low"],
                         ["category", "confidence", "survivor_name", "survivor_qid", "loser_name", "loser_qid",
                          "evidence"])]

    names = R.get("names")
    if names is not None:
        kinds = Counter(re.sub(r" '.*", "", i).split(":")[0] for n in names for i in n["issues"])
        lines += ["## Names (C5) — `names.csv`, `name-conventions.json`", "",
                  "Conventions: " + "; ".join(f"{k}: {v}" for k, v in R.get("name_conventions", {}).items()
                                              if k != "lower_first"), "",
                  "Issues: " + ", ".join(f"{k} {v}" for k, v in kinds.most_common()), "",
                  f"Mechanical renames: {sum(1 for n in names if n['apply'])}.", "",
                  _table(names, ["name", "entity_type", "issues", "proposed_name"])]

    text = R.get("text")
    if text is not None:
        lines += ["## Text (C6, report only) — `text-flags.csv`", "",
                  "By check: " + ", ".join(f"{k} {v}" for k, v in Counter(f["check"] for f in text).items()), "",
                  _table([f for f in text if f["severity"] == "high"] + [f for f in text if f["check"] == "text_type"],
                         ["name", "entity_type", "check", "detail", "summary"])]

    rel = R.get("relations")
    if rel is not None:
        lines += ["## Relationships (C7, report only) — `relation-flags.csv`", "",
                  "By check: " + ", ".join(f"{k} {v}" for k, v in Counter(f["check"] for f in rel).items()) +
                  ". Endpoint-type problems by relation: " + ", ".join(
                      f"{k} {v}" for k, v in Counter(f["relationship_type"] for f in rel
                                                     if f["check"] == "endpoint_type").most_common(8)), "",
                  _table(rel, ["relationship_type", "source_name", "source_type", "target_name", "target_type",
                               "check", "detail"])]

    refs = R.get("stories")
    if refs is not None:
        probs = [r for r in refs if r["problems"]]
        lines += ["## Battle maps (C8) — `story-fixes.md`, `story-refs.csv`", "",
                  f"{len(refs)} references in {len({r['story'] for r in refs})} stories; {len(probs)} with problems.",
                  "", _table(probs, ["story", "where", "name", "qid", "problems", "proposed_qid"])]
        write_story_fixes(out, refs, audit)

    extra = (R.get("notes") or []) + _note_file(out / "notes.txt")
    if extra:
        lines += ["## Notes", ""] + [f"- {n}" for n in extra] + [""]
    (out / "report.md").write_text("\n".join(lines))


def write_story_fixes(out, refs, audit) -> None:
    lines = ["# Story-side QID fixes", "",
             "The audit never edits story files. Apply these in the story source "
             "(`pipeline/map_stories/stories/*.py`), rebuild the JSON and run "
             "`php artisan map-stories:sync`.", "",
             "Format: `file: path → old QID → new QID (evidence)`.", ""]
    fixes = [r for r in refs if r["problems"] and (r["proposed_qid"] or r["qid"])]
    if not fixes:
        lines.append("_No story-side QID fixes._")
    for r in fixes:
        new = r["proposed_qid"] or "(remove the QID; no single correct one found)"
        if r["qid"] and not r["proposed_qid"] and all(p.startswith("DB ") or "share the QID" in p for p in r["problems"]):
            continue  # DB-side problem only; listed below
        lines.append(f"- file: api/resources/map-stories/{r['story']} (source {r['source']}) {r['where']} "
                     f"'{r['name']}' → {r['qid'] or '(none)'} → {new} "
                     f"({'; '.join(r['problems'])}{'; ' + r['evidence'] if r['evidence'] else ''})")
    db = [r for r in refs if r["qid"] and any(p.startswith("DB ") or "share the QID" in p or "not in the atlas" in p
                                              for p in r["problems"] + [r["db_row"]])]
    lines += ["", "## DB side (rows the story QIDs resolve to)", ""]
    for r in db:
        lines.append(f"- {r['story']} {r['where']} {r['qid']} '{r['name']}': {r['db_row']}"
                     + (f" — {'; '.join(p for p in r['problems'] if p.startswith('DB ') or 'share' in p)}"))
    creates = [r for r in refs if (r["proposed_qid"] or r["qid"]) and
               (r["proposed_qid"] or r["qid"]) not in {x.qid for x in audit.rows.values() if x.qid}]
    lines += ["", "## Rows to create (no atlas row carries the QID)", ""]
    seen = set()
    for r in creates:
        q = r["proposed_qid"] or r["qid"]
        if q in seen:
            continue
        seen.add(q)
        lines.append(f"- {q} '{r['name']}' ({r['role']}, {r['story']}) — {r.get('evidence') or r.get('wd_description', '')}")
    extra = (audit.results.get("story_notes") or []) + _note_file(out / "story-notes.txt")
    if extra:
        lines += ["", "## Notes", ""] + [f"- {n}" for n in extra]
    (out / "story-fixes.md").write_text("\n".join(lines) + "\n")
